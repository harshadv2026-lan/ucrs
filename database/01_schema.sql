-- =============================================================================
-- University Course Registration System (UCRS)
-- FILE: 01_schema.sql
-- Description: Oracle 12c+ DDL for all tables, sequences, and constraints
--
-- EXECUTION ORDER: Run this file first before any other scripts.
--
-- NOTE ON CIRCULAR FK:
--   DEPARTMENT.HOD_ID -> FACULTY.Faculty_ID
--   FACULTY.Dept_ID   -> DEPARTMENT.Dept_ID
--   Oracle resolves this via a DEFERRABLE INITIALLY DEFERRED constraint on
--   DEPARTMENT.HOD_ID.  The FK is defined after FACULTY is created.
--   During DML you can SET CONSTRAINTS ALL DEFERRED within a transaction to
--   insert both rows before the constraint is checked at COMMIT time.
-- =============================================================================

SET SERVEROUTPUT ON SIZE UNLIMITED;

-- ---------------------------------------------------------------------------
-- Helper block: drop tables in reverse-dependency order (safe re-run)
-- ---------------------------------------------------------------------------
BEGIN
    -- Drop junction / child tables first
    FOR t IN (
        SELECT table_name
        FROM   user_tables
        WHERE  table_name IN (
                   'PREREQUISITE','REGISTRATION','COURSE_OFFERING',
                   'SEMESTER','COURSE','STUDENT','FACULTY','DEPARTMENT'
               )
        ORDER BY CASE table_name
                     WHEN 'PREREQUISITE'     THEN 1
                     WHEN 'REGISTRATION'     THEN 2
                     WHEN 'COURSE_OFFERING'  THEN 3
                     WHEN 'SEMESTER'         THEN 4
                     WHEN 'COURSE'           THEN 5
                     WHEN 'STUDENT'          THEN 6
                     WHEN 'FACULTY'          THEN 7
                     WHEN 'DEPARTMENT'       THEN 8
                 END
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
        DBMS_OUTPUT.PUT_LINE('Dropped table: ' || t.table_name);
    END LOOP;
END;
/

-- ---------------------------------------------------------------------------
-- Helper block: drop sequences (safe re-run)
-- ---------------------------------------------------------------------------
BEGIN
    FOR s IN (
        SELECT sequence_name
        FROM   user_sequences
        WHERE  sequence_name IN (
                   'SEQ_DEPT_ID','SEQ_FACULTY_ID','SEQ_SEMESTER_ID',
                   'SEQ_OFFERING_ID','SEQ_REG_ID'
               )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
        DBMS_OUTPUT.PUT_LINE('Dropped sequence: ' || s.sequence_name);
    END LOOP;
END;
/

-- =============================================================================
-- SEQUENCES
-- Each sequence drives the surrogate PK of its respective table.
-- =============================================================================

-- Department IDs: 100, 101, 102 …
CREATE SEQUENCE SEQ_DEPT_ID
    START WITH 100
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- Faculty IDs: 1, 2, 3 …
CREATE SEQUENCE SEQ_FACULTY_ID
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- Semester IDs: 1, 2, 3 …
CREATE SEQUENCE SEQ_SEMESTER_ID
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- Course Offering IDs: 1, 2, 3 …
CREATE SEQUENCE SEQ_OFFERING_ID
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- Registration IDs: 1, 2, 3 …
CREATE SEQUENCE SEQ_REG_ID
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- =============================================================================
-- TABLE 1: DEPARTMENT
-- Created WITHOUT the HOD_ID FK initially to break the circular dependency.
-- The FK to FACULTY is added later (step 3) as DEFERRABLE INITIALLY DEFERRED.
-- =============================================================================
CREATE TABLE DEPARTMENT (
    Dept_ID    NUMBER          CONSTRAINT PK_DEPARTMENT PRIMARY KEY,
    Dept_Name  VARCHAR2(100)   CONSTRAINT NN_DEPT_NAME  NOT NULL,
    HOD_ID     NUMBER          -- FK added later; references FACULTY(Faculty_ID)
);

COMMENT ON TABLE  DEPARTMENT          IS 'University academic departments';
COMMENT ON COLUMN DEPARTMENT.Dept_ID  IS 'Surrogate PK generated by SEQ_DEPT_ID';
COMMENT ON COLUMN DEPARTMENT.HOD_ID   IS 'FK to FACULTY – Head of Department (DEFERRABLE)';

-- =============================================================================
-- TABLE 2: FACULTY
-- Depends on DEPARTMENT for Dept_ID FK.
-- =============================================================================
CREATE TABLE FACULTY (
    Faculty_ID   NUMBER          CONSTRAINT PK_FACULTY    PRIMARY KEY,
    First_Name   VARCHAR2(50)    CONSTRAINT NN_FAC_FNAME  NOT NULL,
    Last_Name    VARCHAR2(50)    CONSTRAINT NN_FAC_LNAME  NOT NULL,
    Email        VARCHAR2(100)   CONSTRAINT UQ_FAC_EMAIL  UNIQUE,
    Phone        VARCHAR2(20),
    Designation  VARCHAR2(50),
    Dept_ID      NUMBER          CONSTRAINT NN_FAC_DEPT   NOT NULL,
    -- FK: every faculty member belongs to exactly one department
    CONSTRAINT FK_FAC_DEPT
        FOREIGN KEY (Dept_ID) REFERENCES DEPARTMENT(Dept_ID)
);

COMMENT ON TABLE  FACULTY              IS 'Teaching and administrative faculty';
COMMENT ON COLUMN FACULTY.Designation  IS 'e.g. Professor, Assoc. Professor, Asst. Professor, Lecturer';

-- =============================================================================
-- STEP 3: Add HOD_ID FK to DEPARTMENT (now that FACULTY exists)
-- DEFERRABLE INITIALLY DEFERRED: constraint is checked at COMMIT, not at each
-- row insert, which allows inserting department and faculty in the same txn.
-- =============================================================================
ALTER TABLE DEPARTMENT
    ADD CONSTRAINT FK_DEPT_HOD
        FOREIGN KEY (HOD_ID)
        REFERENCES FACULTY(Faculty_ID)
        DEFERRABLE INITIALLY DEFERRED;

-- =============================================================================
-- TABLE 4: STUDENT
-- =============================================================================
CREATE TABLE STUDENT (
    Student_RegNo  VARCHAR2(20)    CONSTRAINT PK_STUDENT    PRIMARY KEY,
    First_Name     VARCHAR2(50)    CONSTRAINT NN_STU_FNAME  NOT NULL,
    Last_Name      VARCHAR2(50)    CONSTRAINT NN_STU_LNAME  NOT NULL,
    Email          VARCHAR2(100)   CONSTRAINT UQ_STU_EMAIL  UNIQUE,
    Phone          VARCHAR2(20),
    DOB            DATE,
    Gender         CHAR(1)         CONSTRAINT CHK_STU_GENDER CHECK (Gender IN ('M','F','O')),
    Address        VARCHAR2(200),
    Dept_ID        NUMBER          CONSTRAINT NN_STU_DEPT   NOT NULL,
    Semester_No    NUMBER(2)       CONSTRAINT CHK_STU_SEM   CHECK (Semester_No BETWEEN 1 AND 10),
    CGPA           NUMBER(4,2)     CONSTRAINT CHK_STU_CGPA  CHECK (CGPA BETWEEN 0 AND 10),
    -- FK: student enrolled in a department
    CONSTRAINT FK_STU_DEPT
        FOREIGN KEY (Dept_ID) REFERENCES DEPARTMENT(Dept_ID)
);

COMMENT ON TABLE  STUDENT               IS 'Enrolled students';
COMMENT ON COLUMN STUDENT.Student_RegNo IS 'University registration number, e.g. 2024CS001';
COMMENT ON COLUMN STUDENT.Semester_No   IS 'Current academic semester (1-10)';
COMMENT ON COLUMN STUDENT.CGPA          IS 'Cumulative Grade Point Average on 10-point scale';

-- =============================================================================
-- TABLE 5: COURSE
-- =============================================================================
CREATE TABLE COURSE (
    Course_ID    VARCHAR2(20)    CONSTRAINT PK_COURSE    PRIMARY KEY,
    Course_Name  VARCHAR2(100)   CONSTRAINT NN_CRS_NAME  NOT NULL,
    Credits      NUMBER(2)       CONSTRAINT NN_CRS_CRED  NOT NULL
                                 CONSTRAINT CHK_CRS_CRED CHECK (Credits BETWEEN 1 AND 6),
    Description  VARCHAR2(500),
    Dept_ID      NUMBER          CONSTRAINT NN_CRS_DEPT  NOT NULL,
    -- FK: course offered by a department
    CONSTRAINT FK_CRS_DEPT
        FOREIGN KEY (Dept_ID) REFERENCES DEPARTMENT(Dept_ID)
);

COMMENT ON TABLE  COURSE            IS 'Academic course catalogue';
COMMENT ON COLUMN COURSE.Credits    IS 'Credit hours (1-6)';
COMMENT ON COLUMN COURSE.Course_ID  IS 'Alphanumeric course code, e.g. CS101';

-- =============================================================================
-- TABLE 6: SEMESTER
-- =============================================================================
CREATE TABLE SEMESTER (
    Semester_ID    NUMBER          CONSTRAINT PK_SEMESTER   PRIMARY KEY,
    Semester_Name  VARCHAR2(50)    CONSTRAINT NN_SEM_NAME   NOT NULL,
    Academic_Year  VARCHAR2(20),
    Start_Date     DATE,
    End_Date       DATE,
    Is_Active      CHAR(1)         DEFAULT 'N'
                                   CONSTRAINT CHK_SEM_ACTIVE CHECK (Is_Active IN ('Y','N')),
    -- Business rule: end date must be after start date
    CONSTRAINT CHK_SEM_DATES CHECK (End_Date IS NULL OR Start_Date IS NULL OR End_Date > Start_Date)
);

COMMENT ON TABLE  SEMESTER             IS 'Academic semesters / terms';
COMMENT ON COLUMN SEMESTER.Is_Active   IS 'Y = currently active semester; only one should be Y at a time';
COMMENT ON COLUMN SEMESTER.Semester_ID IS 'Generated by SEQ_SEMESTER_ID';

-- =============================================================================
-- TABLE 7: COURSE_OFFERING
-- Represents a specific instance of a course taught in a semester by a faculty.
-- =============================================================================
CREATE TABLE COURSE_OFFERING (
    Offering_ID   NUMBER          CONSTRAINT PK_OFFERING    PRIMARY KEY,
    Course_ID     VARCHAR2(20)    CONSTRAINT NN_OFF_CRS     NOT NULL,
    Semester_ID   NUMBER          CONSTRAINT NN_OFF_SEM     NOT NULL,
    Faculty_ID    NUMBER          CONSTRAINT NN_OFF_FAC     NOT NULL,
    Max_Seats     NUMBER          DEFAULT 60
                                  CONSTRAINT CHK_OFF_SEATS  CHECK (Max_Seats > 0),
    Schedule      VARCHAR2(100),  -- e.g. 'MWF 09:00-10:00 Room 201'
    -- FKs
    CONSTRAINT FK_OFF_CRS
        FOREIGN KEY (Course_ID)   REFERENCES COURSE(Course_ID),
    CONSTRAINT FK_OFF_SEM
        FOREIGN KEY (Semester_ID) REFERENCES SEMESTER(Semester_ID),
    CONSTRAINT FK_OFF_FAC
        FOREIGN KEY (Faculty_ID)  REFERENCES FACULTY(Faculty_ID),
    -- Unique: a course can be offered only once per semester per faculty slot
    CONSTRAINT UQ_OFF_CRS_SEM_FAC UNIQUE (Course_ID, Semester_ID, Faculty_ID)
);

COMMENT ON TABLE  COURSE_OFFERING            IS 'A course delivered in a particular semester by a particular faculty';
COMMENT ON COLUMN COURSE_OFFERING.Max_Seats  IS 'Maximum student enrolments allowed (default 60)';
COMMENT ON COLUMN COURSE_OFFERING.Schedule   IS 'Human-readable timetable string';

-- =============================================================================
-- TABLE 8: REGISTRATION
-- Student enrolment in a course offering.
-- UNIQUE(Student_RegNo, Offering_ID) prevents duplicate registration.
-- =============================================================================
CREATE TABLE REGISTRATION (
    Reg_ID             NUMBER          CONSTRAINT PK_REGISTRATION PRIMARY KEY,
    Student_RegNo      VARCHAR2(20)    CONSTRAINT NN_REG_STU  NOT NULL,
    Offering_ID        NUMBER          CONSTRAINT NN_REG_OFF  NOT NULL,
    Registration_Date  DATE            DEFAULT SYSDATE,
    Grade              VARCHAR2(2),    -- e.g. A+, A, B+, B, C, F
    Status             VARCHAR2(20)    DEFAULT 'REGISTERED'
                                       CONSTRAINT CHK_REG_STATUS
                                           CHECK (Status IN ('REGISTERED','DROPPED','COMPLETED')),
    -- FKs
    CONSTRAINT FK_REG_STU
        FOREIGN KEY (Student_RegNo) REFERENCES STUDENT(Student_RegNo),
    CONSTRAINT FK_REG_OFF
        FOREIGN KEY (Offering_ID)   REFERENCES COURSE_OFFERING(Offering_ID),
    -- Business rule: a student can register for a given offering only once
    CONSTRAINT UQ_REG_STU_OFF UNIQUE (Student_RegNo, Offering_ID)
);

COMMENT ON TABLE  REGISTRATION              IS 'Student course registrations per semester offering';
COMMENT ON COLUMN REGISTRATION.Grade        IS 'Letter grade awarded on course completion (NULL until graded)';
COMMENT ON COLUMN REGISTRATION.Status       IS 'REGISTERED | DROPPED | COMPLETED';
COMMENT ON COLUMN REGISTRATION.Reg_ID       IS 'Generated by SEQ_REG_ID';

-- =============================================================================
-- TABLE 9: PREREQUISITE
-- Many-to-many self-join on COURSE.
-- Composite PK (Course_ID, Prereq_Course_ID) ensures no duplicate prereqs.
-- =============================================================================
CREATE TABLE PREREQUISITE (
    Course_ID         VARCHAR2(20)  CONSTRAINT NN_PRE_CRS      NOT NULL,
    Prereq_Course_ID  VARCHAR2(20)  CONSTRAINT NN_PRE_PREREQ   NOT NULL,
    -- Composite PK
    CONSTRAINT PK_PREREQUISITE PRIMARY KEY (Course_ID, Prereq_Course_ID),
    -- FKs: both columns reference COURSE
    CONSTRAINT FK_PRE_CRS
        FOREIGN KEY (Course_ID)        REFERENCES COURSE(Course_ID),
    CONSTRAINT FK_PRE_PREREQ
        FOREIGN KEY (Prereq_Course_ID) REFERENCES COURSE(Course_ID),
    -- Business rule: a course cannot be its own prerequisite
    CONSTRAINT CHK_PRE_NO_SELF CHECK (Course_ID <> Prereq_Course_ID)
);

COMMENT ON TABLE  PREREQUISITE               IS 'Course prerequisites (course -> required prior course)';
COMMENT ON COLUMN PREREQUISITE.Course_ID     IS 'The course that has a prerequisite';
COMMENT ON COLUMN PREREQUISITE.Prereq_Course_ID IS 'The course that must be completed first';

-- =============================================================================
-- INDEXES (performance)
-- Oracle automatically creates indexes for PK/UNIQUE constraints.
-- Additional indexes on heavily-queried FK columns.
-- =============================================================================
CREATE INDEX IDX_FAC_DEPT       ON FACULTY         (Dept_ID);
CREATE INDEX IDX_STU_DEPT       ON STUDENT         (Dept_ID);
CREATE INDEX IDX_CRS_DEPT       ON COURSE          (Dept_ID);
CREATE INDEX IDX_OFF_SEM        ON COURSE_OFFERING (Semester_ID);
CREATE INDEX IDX_OFF_FAC        ON COURSE_OFFERING (Faculty_ID);
CREATE INDEX IDX_REG_STU        ON REGISTRATION    (Student_RegNo);
CREATE INDEX IDX_REG_OFF        ON REGISTRATION    (Offering_ID);
CREATE INDEX IDX_REG_STATUS     ON REGISTRATION    (Status);
CREATE INDEX IDX_PRE_PREREQ     ON PREREQUISITE    (Prereq_Course_ID);

-- =============================================================================
-- Verify creation
-- =============================================================================
SELECT table_name, num_rows
FROM   user_tables
WHERE  table_name IN (
           'DEPARTMENT','FACULTY','STUDENT','COURSE',
           'SEMESTER','COURSE_OFFERING','REGISTRATION','PREREQUISITE'
       )
ORDER BY table_name;

PROMPT '==> 01_schema.sql completed successfully.';
